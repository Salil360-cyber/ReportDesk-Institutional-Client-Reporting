-- ReportDesk: institutional client reporting dataset (synthetic). PostgreSQL.
-- Run this whole file once in pgAdmin Query Tool (F5). It recreates every table.

DROP TABLE IF EXISTS client_queries, report_tracker, benchmark_returns, cash_flows, holdings, prices, securities, clients, benchmarks CASCADE;

CREATE TABLE benchmarks (
    benchmark_id   VARCHAR(10) PRIMARY KEY,
    benchmark_name VARCHAR(60) NOT NULL
);

CREATE TABLE clients (
    client_id      VARCHAR(5)  PRIMARY KEY,
    client_name    VARCHAR(60) NOT NULL,
    client_type    VARCHAR(30) NOT NULL,
    country        VARCHAR(30) NOT NULL,
    benchmark_id   VARCHAR(10) NOT NULL REFERENCES benchmarks(benchmark_id),
    deadline_working_days INT  NOT NULL,
    analyst        VARCHAR(20) NOT NULL
);

CREATE TABLE securities (
    security_id    VARCHAR(10) PRIMARY KEY,
    isin           VARCHAR(12),
    security_name  VARCHAR(60) NOT NULL,
    asset_class    VARCHAR(20) NOT NULL,
    sector         VARCHAR(30) NOT NULL,
    country        VARCHAR(30) NOT NULL
);

CREATE TABLE prices (
    security_id    VARCHAR(10) NOT NULL,
    price_date     DATE        NOT NULL,
    price          NUMERIC(14,4) NOT NULL,
    PRIMARY KEY (security_id, price_date)
);

-- No primary key on purpose: real feeds can contain duplicates, and finding them is one of our checks.
CREATE TABLE holdings (
    client_id      VARCHAR(5)  NOT NULL,
    security_id    VARCHAR(10) NOT NULL,
    as_of_date     DATE        NOT NULL,
    quantity       NUMERIC(16,2) NOT NULL
);

CREATE TABLE cash_flows (
    client_id      VARCHAR(5)  NOT NULL,
    flow_date      DATE        NOT NULL,
    amount         NUMERIC(16,2) NOT NULL,
    flow_type      VARCHAR(15) NOT NULL
);

CREATE TABLE benchmark_returns (
    benchmark_id   VARCHAR(10) NOT NULL REFERENCES benchmarks(benchmark_id),
    month_end      DATE        NOT NULL,
    return_pct     NUMERIC(8,6) NOT NULL,
    PRIMARY KEY (benchmark_id, month_end)
);

CREATE TABLE report_tracker (
    client_id      VARCHAR(5)  NOT NULL REFERENCES clients(client_id),
    report_month   DATE        NOT NULL,
    analyst        VARCHAR(20) NOT NULL,
    deadline_date  DATE        NOT NULL,
    data_ready_date DATE,
    sent_date      DATE,
    status         VARCHAR(20) NOT NULL,
    PRIMARY KEY (client_id, report_month)
);

CREATE TABLE client_queries (
    query_id       VARCHAR(6)  PRIMARY KEY,
    client_id      VARCHAR(5)  NOT NULL REFERENCES clients(client_id),
    received_date  DATE        NOT NULL,
    query_type     VARCHAR(30) NOT NULL,
    priority       VARCHAR(10) NOT NULL,
    status         VARCHAR(15) NOT NULL,
    resolved_date  DATE
);

